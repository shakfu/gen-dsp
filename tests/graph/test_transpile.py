class TestStatefulFaithful:
    def test_history_declares_and_writes_back(self) -> None:
        g = _wrap(
            [
                BinOp(id="sum", op="add", a="x", b="fb"),
                History(id="fb", init=0.0, input="sum"),
            ],
            inputs=[AudioInput(id="x")],
            source="sum",
        )
        code = transpile_to_genexpr(g)
        assert "History fb(0.0);" in code
        assert "sum = in1 + fb;" in code
        # The history read needs no compute line; only the store-for-next line.
        assert "fb = sum;" in code

    def test_delta_is_native(self) -> None:
        g = _wrap(
            [Pass(id="x", a="sig"), Delta(id="d", a="x")],
            inputs=[AudioInput(id="sig")],
            source="d",
        )
        assert "d = delta(x);" in transpile_to_genexpr(g)

    def test_change_is_faithful_not_native(self) -> None:
        # gen~ `change` returns sign of difference; ours is a boolean. Must be
        # emitted via History, NOT the native `change` operator.
        g = _wrap([Change(id="c", a="sig")], inputs=[AudioInput(id="sig")], source="c")
        code = transpile_to_genexpr(g)
        assert "History c_prev(0.0);" in code
        assert "c = (in1 != c_prev ? 1 : 0);" in code
        assert "c_prev = in1;" in code
        assert "= change(" not in code

    def test_accum_faithful(self) -> None:
        g = _wrap(
            [Accum(id="a", incr="sig", reset=0.0)],
            inputs=[AudioInput(id="sig")],
            source="a",
        )
        code = transpile_to_genexpr(g)
        assert "History a_sum(0.0);" in code
        assert "a_s = (0.0 > 0 ? 0 : a_sum);" in code
        assert "a_s = a_s + in1;" in code
        assert "a_sum = a_s;" in code

    def test_counter_faithful(self) -> None:
        g = _wrap(
            [Counter(id="cnt", trig="sig", max=4.0)],
            inputs=[AudioInput(id="sig")],
            source="cnt",
        )
        code = transpile_to_genexpr(g)
        assert "History cnt_count(0.0);" in code
        assert "History cnt_ptrig(0.0);" in code
        assert "cnt_inc = (cnt_inc >= trunc(4.0) ? 0 : cnt_inc);" in code

    def test_elapsed_faithful(self) -> None:
        g = _wrap([Elapsed(id="el")])
        code = transpile_to_genexpr(g)
        assert "History el_count(0.0);" in code
        assert "el = el_count;" in code
        assert "el_count = el_count + 1;" in code

    def test_samplerate_native(self) -> None:
        g = _wrap([SampleRate(id="sr")])
        assert "sr = samplerate;" in transpile_to_genexpr(g)


