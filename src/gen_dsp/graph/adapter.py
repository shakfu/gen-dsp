"""gen-dsp adapter: bridge graph output to gen-dsp platform backends.

Generates adapter C++ code that implements gen-dsp's ``_ext.h`` wrapper
interface by delegating to the graph compiled API.  Also generates
a ``manifest.json`` compatible with ``gen_dsp.core.manifest.Manifest``.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import TYPE_CHECKING

# Re-exported (documented API); the build-file generators live in a module without the
# pydantic dependency, so the cignal frontend can use them.
from gen_dsp.core.wrapper_build import generate_graph_build_file
from gen_dsp.graph.compile import compile_graph
from gen_dsp.graph.compile.common import _to_pascal
from gen_dsp.graph.models import Buffer, Graph
from gen_dsp.version import __version__

if TYPE_CHECKING:
    from gen_dsp.core.manifest import Manifest

__all__ = [
    "SUPPORTED_PLATFORMS",
    "compile_for_gen_dsp",
    "generate_adapter_cpp",
    "generate_graph_build_file",
    "generate_manifest",
    "generate_manifest_obj",
]

# Platform key -> (common-header macro prefix, namespace suffix)
_PLATFORM_INFO: dict[str, tuple[str, str]] = {
    "chuck": ("CHUCK_EXT_NAME", "_chugin"),
    "clap": ("CLAP_EXT_NAME", "_clap"),
    "au": ("AU_EXT_NAME", "_au"),
    "vst3": ("VST3_EXT_NAME", "_vst3"),
    "lv2": ("LV2_EXT_NAME", "_lv2"),
    "sc": ("SC_EXT_NAME", "_sc"),
    "vcvrack": ("VCVRACK_EXT_NAME", "_vcvrack"),
    "daisy": ("DAISY_EXT_NAME", "_daisy"),
    "circle": ("CIRCLE_EXT_NAME", "_circle"),
    "pd": ("PD_EXT_NAME", "_pd"),
    "max": ("MAX_EXT_NAME", "_max"),
    "webaudio": ("WEBAUDIO_EXT_NAME", "_webaudio"),
    "standalone": ("STANDALONE_EXT_NAME", "_standalone"),
    "csound": ("CSOUND_EXT_NAME", "_csound"),
    "auv3": ("AUV3_EXT_NAME", "_auv3"),
    "ssp": ("SSP_EXT_NAME", "_ssp"),
    "nice": ("NICE_EXT_NAME", "_nice"),
}

SUPPORTED_PLATFORMS = set(_PLATFORM_INFO.keys())


def generate_adapter_cpp(graph: Graph, platform: str) -> str:
    """Generate the ``_ext_{platform}.cpp`` adapter source.

    This replaces the genlib-side wrapper with graph calls while
    keeping gen-dsp's platform-side code unchanged.

    Args:
        graph: Compiled DSP graph.
        platform: gen-dsp platform key (e.g. ``"chuck"``, ``"clap"``).

    Returns:
        Complete C++ source as a string.

    Raises:
        ValueError: If *platform* is not a recognised gen-dsp platform.
    """
    if platform not in _PLATFORM_INFO:
        raise ValueError(
            f"Unknown platform {platform!r}; supported: {sorted(_PLATFORM_INFO)}"
        )

    name = graph.name
    struct = _to_pascal(name) + "State"
    # Max uses t_sample = double; all other platforms use float.
    use_double = platform == "max"
    st = "double" if use_double else "float"

    lines: list[str] = []
    w = lines.append

    w(f"// _ext_{platform}.cpp -- graph adapter for gen-dsp {platform} backend")
    w("// Generated by gen-dsp (graph frontend)")
    w("")
    w(f'#include "gen_ext_common_{platform}.h"')
    w("")
    w("// Include graph compiled code")
    w(f'#include "{name}.cpp"')
    w("")
    w("typedef void GenState;")
    w("")
    w("namespace WRAPPER_NAMESPACE {")
    w("")

    # -- lifecycle
    w(f"GenState* wrapper_create({st} sr, long bs) {{")
    w("    (void)bs;")
    w(f"    return (GenState*){name}_create((float)sr);")
    w("}")
    w("")
    w("void wrapper_destroy(GenState* state) {")
    w(f"    {name}_destroy(({struct}*)state);")
    w("}")
    w("")
    w("void wrapper_reset(GenState* state) {")
    w(f"    {name}_reset(({struct}*)state);")
    w("}")
    w("")

    # -- perform
    if use_double:
        # Max passes double** I/O buffers; graph processes float internally.
        # Convert at the boundary.
        num_inputs = len(graph.inputs)
        num_outputs = len(graph.outputs)
        w(f"void wrapper_perform(GenState* state, {st}** ins, long numins,")
        w(f"                     {st}** outs, long numouts, long n) {{")
        w("    (void)numins; (void)numouts;")
        # Allocate float scratch buffers on the stack for small block sizes.
        for i in range(num_inputs):
            w(f"    float in{i}[n];")
        for i in range(num_outputs):
            w(f"    float out{i}[n];")
        w(f"    float* fins[{max(num_inputs, 1)}];")
        w(f"    float* fouts[{max(num_outputs, 1)}];")
        for i in range(num_inputs):
            w(f"    fins[{i}] = in{i};")
            w(f"    for (long j = 0; j < n; j++) in{i}[j] = (float)ins[{i}][j];")
        for i in range(num_outputs):
            w(f"    fouts[{i}] = out{i};")
        w(f"    {name}_perform(({struct}*)state, fins, fouts, (int)n);")
        for i in range(num_outputs):
            w(f"    for (long j = 0; j < n; j++) outs[{i}][j] = (double)out{i}[j];")
        w("}")
    else:
        w(f"void wrapper_perform(GenState* state, {st}** ins, long numins,")
        w(f"                     {st}** outs, long numouts, long n) {{")
        w("    (void)numins; (void)numouts;")
        w(f"    {name}_perform(({struct}*)state, ins, outs, (int)n);")
        w("}")
    w("")

    # -- I/O counts
    w(f"int wrapper_num_inputs() {{ return {name}_num_inputs(); }}")
    w(f"int wrapper_num_outputs() {{ return {name}_num_outputs(); }}")
    w(f"int wrapper_num_params() {{ return {name}_num_params(); }}")
    w("")

    # -- param introspection
    w("const char* wrapper_param_name(GenState* state, int index) {")
    w("    (void)state;")
    w(f"    return {name}_param_name(index);")
    w("}")
    w("")
    w("const char* wrapper_param_units(GenState* state, int index) {")
    w("    (void)state; (void)index;")
    w('    return "";')
    w("}")
    w("")
    w(f"{st} wrapper_param_min(GenState* state, int index) {{")
    w("    (void)state;")
    w(f"    return ({st}){name}_param_min(index);")
    w("}")
    w("")
    w(f"{st} wrapper_param_max(GenState* state, int index) {{")
    w("    (void)state;")
    w(f"    return ({st}){name}_param_max(index);")
    w("}")
    w("")
    w("char wrapper_param_hasminmax(GenState* state, int index) {")
    w("    (void)state; (void)index;")
    w("    return 1;")
    w("}")
    w("")
    w(f"void wrapper_set_param(GenState* state, int index, {st} value) {{")
    w(f"    {name}_set_param(({struct}*)state, index, (float)value);")
    w("}")
    w("")
    w(f"{st} wrapper_get_param(GenState* state, int index) {{")
    w(f"    return ({st}){name}_get_param(({struct}*)state, index);")
    w("}")
    w("")

    # -- buffers
    w(f"int wrapper_num_buffers() {{ return {name}_num_buffers(); }}")
    w("")
    w("const char* wrapper_buffer_name(int index) {")
    w(f"    return {name}_buffer_name(index);")
    w("}")
    w("")
    w("int wrapper_load_buffer(int index, const char* path) {")
    w("    (void)index; (void)path;")
    w("    return -1;  // graph-compiled code does not support runtime buffer loading")
    w("}")
    w("")
    w("} // namespace WRAPPER_NAMESPACE")
    w("")

    return "\n".join(lines)


def generate_manifest_obj(graph: Graph) -> Manifest:
    """Generate a ``Manifest`` dataclass from a DSP graph.

    Args:
        graph: The DSP graph.

    Returns:
        A gen-dsp ``Manifest`` instance.
    """
    from gen_dsp.core.manifest import Manifest, ParamInfo

    buffer_ids = [n.id for n in graph.nodes if isinstance(n, Buffer)]
    params = [
        ParamInfo(
            index=i,
            name=p.name,
            has_minmax=True,
            min=p.min,
            max=p.max,
            default=p.default,
        )
        for i, p in enumerate(graph.params)
    ]
    return Manifest(
        gen_name=graph.name,
        num_inputs=len(graph.inputs),
        num_outputs=len(graph.outputs),
        params=params,
        buffers=buffer_ids,
        source="graph",
        version=__version__,
    )


def generate_manifest(graph: Graph) -> str:
    """Generate a ``manifest.json`` compatible with gen-dsp's ``Manifest``.

    Args:
        graph: The DSP graph.

    Returns:
        JSON string.
    """
    buffer_ids = [n.id for n in graph.nodes if isinstance(n, Buffer)]
    data = {
        "gen_name": graph.name,
        "num_inputs": len(graph.inputs),
        "num_outputs": len(graph.outputs),
        "params": [
            {
                "index": i,
                "name": p.name,
                "has_minmax": True,
                "min": p.min,
                "max": p.max,
                "default": p.default,
            }
            for i, p in enumerate(graph.params)
        ],
        "buffers": buffer_ids,
        "source": "graph",
        "version": __version__,
    }
    return json.dumps(data, indent=2) + "\n"


def compile_for_gen_dsp(
    graph: Graph,
    output_dir: str | Path,
    platform: str,
) -> Path:
    """Compile a graph and generate gen-dsp adapter files.

    Writes three files to *output_dir*:

    - ``{name}.cpp`` -- compiled graph C++
    - ``_ext_{platform}.cpp`` -- gen-dsp adapter
    - ``manifest.json`` -- gen-dsp-compatible manifest

    Args:
        graph: The DSP graph.
        output_dir: Where to write files.
        platform: gen-dsp platform key.

    Returns:
        Path to the output directory.
    """
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    code = compile_graph(graph)
    (out / f"{graph.name}.cpp").write_text(code)

    adapter = generate_adapter_cpp(graph, platform)
    (out / f"_ext_{platform}.cpp").write_text(adapter)

    manifest = generate_manifest(graph)
    (out / "manifest.json").write_text(manifest)

    return out
